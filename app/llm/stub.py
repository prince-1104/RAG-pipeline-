from __future__ import annotations

import uuid
from typing import Any

from app.llm.base import LLMResult


class StubLLMClient:
    """
    Deterministic stub used for local/dev to validate RAG + schema + citations plumbing
    without requiring provider keys.
    """

    def generate_json(self, *, system_prompt: str, user_prompt: str, json_schema: dict[str, Any]) -> LLMResult:
        # The user_prompt includes context entries with chunk ids and excerpts.
        # We'll emit a minimal valid payload that references the first chunk we see.
        chunk_id = None
        document_id = None
        storage_uri = None
        page_start = 1
        page_end = 1
        excerpt = None

        for line in user_prompt.splitlines():
            if line.startswith("CHUNK_ID:") and chunk_id is None:
                chunk_id = line.split("CHUNK_ID:", 1)[1].strip()
            if line.startswith("DOCUMENT_ID:") and document_id is None:
                document_id = line.split("DOCUMENT_ID:", 1)[1].strip()
            if line.startswith("STORAGE_URI:") and storage_uri is None:
                storage_uri = line.split("STORAGE_URI:", 1)[1].strip()
            if line.startswith("PAGES:") and ":" in line:
                rng = line.split("PAGES:", 1)[1].strip()
                if "-" in rng:
                    a, b = rng.split("-", 1)
                    page_start, page_end = int(a), int(b)
            if line.startswith("EXCERPT:") and excerpt is None:
                excerpt = line.split("EXCERPT:", 1)[1].strip()
            if line.startswith("TEXT:") and excerpt is None:
                # Fallback: use first part of TEXT if EXCERPT not found
                text_line = line.split("TEXT:", 1)[1].strip()
                if text_line:
                    excerpt = text_line[:240].replace("\n", " ")

        # Extract key words from excerpt to pass guardrail token overlap check
        # Take words >= 5 chars from excerpt for answer/explanation
        excerpt_words = []
        if excerpt:
            import re
            words = re.findall(r'\b[a-z]{5,}\b', excerpt.lower())
            excerpt_words = words[:10]  # Take first 10 words >= 5 chars
        
        # Build answer/explanation using excerpt words to pass guardrail
        if excerpt_words:
            answer_text = f"The concept involves {', '.join(excerpt_words[:3])} as described in the CBSE material."
            explanation_text = f"This explanation is based on the provided context covering {', '.join(excerpt_words[:5])}."
        else:
            answer_text = "This answer is derived strictly from the provided excerpt."
            explanation_text = "Generated by stub provider for pipeline validation."

        payload = {
            "questions": [
                {
                    "id": str(uuid.uuid4()),
                    "qtype": "short",
                    "difficulty": "easy",
                    "language": "en",
                    "stem": "Explain the key concept mentioned in the provided CBSE context.",
                    "options": None,
                    "answer": answer_text,
                    "explanation": explanation_text,
                    "tags": {"provider": "stub"},
                    "citations": [
                        {
                            "chunk_id": chunk_id or "unknown",
                            "document_id": document_id or "unknown",
                            "storage_uri": storage_uri or "unknown",
                            "page_start": page_start,
                            "page_end": page_end,
                            "excerpt": excerpt or "No excerpt available.",
                        }
                    ],
                }
            ],
            "rejected": [],
        }
        return LLMResult(raw_text=str(payload), parsed_json=payload)


